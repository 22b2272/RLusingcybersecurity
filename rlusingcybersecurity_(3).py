# Prioritized Experience Replay
class PrioritizedReplayBuffer:
    def __init__(self, capacity):
        self.tree = SumTree(capacity)
        self.capacity = capacity

    def store(self, experience):
        max_priority = np.max(self.tree.tree[-self.tree.capacity:])
        if max_priority == 0:
            max_priority = 1
        self.tree.add(max_priority, experience)

    def sample(self, n):
        batch = []
        idxs = []
        segment = self.tree.total() / n
        priorities = []

        for i in range(n):
            a = segment * i
            b = segment * (i + 1)

            s = random.uniform(a, b)
            (idx, p, data) = self.tree.get(s)
            batch.append(data)
            idxs.append(idx)
            priorities.append(p)

        return batch, idxs, np.array(priorities)

    def update(self, idx, priority):
        self.tree.update(idx, priority)

# Dueling DQN Agent
class DuelingDQNAgent:
    def __init__(self, state_size, action_size):
        self.state_size = state_size
        self.action_size = action_size
        self.memory = PrioritizedReplayBuffer(capacity=50000)
        self.gamma = 0.95  # Discount rate
        self.epsilon = 1.0  # Exploration rate
        self.epsilon_min = 0.01
        self.epsilon_decay = 0.995
        self.model = self._build_model()
        self.target_model = self._build_model()
        self.update_target_model()

    def _build_model(self):
        # Dueling architecture
        state_input = layers.Input(shape=(self.state_size,))
        x = layers.Dense(128, activation='relu')(state_input)
        x = layers.Dropout(0.2)(x)
        x = layers.Dense(64, activation='relu')(x)
        x = layers.Dropout(0.2)(x)

        state_value = layers.Dense(1, activation='linear')(x)
        action_advantage = layers.Dense(self.action_size, activation='linear')(x)

        output = layers.Lambda(lambda a: a[0] + a[1] - tf.reduce_mean(a[1], keepdims=True), output_shape=(self.action_size,))([state_value, action_advantage])

        model = models.Model(inputs=state_input, outputs=output)
        model.compile(loss='mse', optimizer=tf.keras.optimizers.Adam(learning_rate=0.001))
        return model

    def update_target_model(self):
        self.target_model.set_weights(self.model.get_weights())

    def remember(self, state, action, reward, next_state, done):
        experience = (state, action, reward, next_state, done)
        self.memory.store(experience)

    def act(self, state):
        if np.random.rand() <= self.epsilon:
            return random.randrange(self.action_size)
        q_values = self.model.predict(state)
        return np.argmax(q_values[0])

    def replay(self, batch_size, beta):
        batch, idxs, priorities = self.memory.sample(batch_size)
        states = np.array([x[0] for x in batch])
        actions = np.array([x[1] for x in batch])
        rewards = np.array([x[2] for x in batch])
        next_states = np.array([x[3] for x in batch])
        dones = np.array([x[4] for x in batch])

        target_q_values = self.target_model.predict(next_states)
        max_target_q_values = np.amax(target_q_values, axis=1)
        y_target = rewards + (1 - dones) * self.gamma * max_target_q_values

        q_values = self.model.predict(states)
        q_values[np.arange(batch_size), actions] = y_target

        td_errors = np.abs(y_target - q_values[np.arange(batch_size), actions])
        for i in range(batch_size):
            idx = idxs[i]
            self.memory.update(idx, td_errors[i])

        loss = self.model.train_on_batch(states, q_values)

        if self.epsilon > self.epsilon_min:
            self.epsilon *= self.epsilon_decay

        return loss

